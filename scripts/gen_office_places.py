#!/usr/bin/env python3
"""Regenerate office_places.py from the tz database's zone.tab (public domain).

Usage: python3 scripts/gen_office_places.py [path/to/zone.tab]   (default: /usr/share/zoneinfo/zone.tab)
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
ISO6709 = re.compile(r"^([+-])(\d{2})(\d{2})(\d{2})?([+-])(\d{3})(\d{2})(\d{2})?$")

ALIASES = {
    "Asia/Calcutta": "Asia/Kolkata", "Asia/Saigon": "Asia/Ho_Chi_Minh", "Asia/Katmandu": "Asia/Kathmandu",
    "Asia/Rangoon": "Asia/Yangon", "Europe/Kiev": "Europe/Kyiv",
    "America/Buenos_Aires": "America/Argentina/Buenos_Aires", "America/Indianapolis": "America/Indiana/Indianapolis",
    "Asia/Chongqing": "Asia/Shanghai", "Asia/Harbin": "Asia/Shanghai", "Australia/ACT": "Australia/Sydney",
    "US/Pacific": "America/Los_Angeles", "US/Mountain": "America/Denver", "US/Central": "America/Chicago",
    "US/Eastern": "America/New_York", "Asia/Istanbul": "Europe/Istanbul", "Atlantic/Faeroe": "Atlantic/Faroe",
    "Pacific/Truk": "Pacific/Chuuk", "Pacific/Ponape": "Pacific/Pohnpei",
}


def parse_coord(text):
    """ISO 6709 `+DDMM+DDDMM` or `+DDMMSS+DDDMMSS` -> (lat, lon) in decimal degrees, 2 decimals."""
    m = ISO6709.match(text)
    if not m:
        raise ValueError("bad coordinate: " + text)
    s1, d1, m1, c1, s2, d2, m2, c2 = m.groups()
    lat = int(d1) + int(m1) / 60 + int(c1 or 0) / 3600
    lon = int(d2) + int(m2) / 60 + int(c2 or 0) / 3600
    return (round(-lat if s1 == "-" else lat, 2), round(-lon if s2 == "-" else lon, 2))


def parse_zone_tab(text):
    out = {}
    for line in text.splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) >= 3:
            out[parts[2].strip()] = parse_coord(parts[1].strip())
    return out


def render(places):
    rows = "".join(f'    "{k}": ({v[0]}, {v[1]}),\n' for k, v in sorted(places.items()))
    al = "".join(f'    "{k}": "{v}",\n' for k, v in ALIASES.items())
    return ('"""Where a time zone is: IANA zone name -> (latitude, longitude), for the office\'s sky.\n\n'
            "GENERATED by scripts/gen_office_places.py from zone.tab of the tz database (public domain, iana.org/time-zones).\n"
            "Each point is the zone's principal city, rounded to 2 decimals: enough for the sun's position, not for a map.\n"
            "Do not edit by hand.\n"
            '"""\n\nPLACES = {\n' + rows + "}\n\n# Names older browsers and systems still return, mapped to the current zone.tab name.\nALIASES = {\n" + al + "}\n\n\n"
            "def place_of(tz):\n"
            '    """(lat, lon) of an IANA zone name, or None for UTC, Etc/*, empty or unknown names."""\n'
            "    if not isinstance(tz, str) or not tz or tz == \"UTC\" or tz.startswith(\"Etc/\"):\n"
            "        return None\n"
            "    return PLACES.get(ALIASES.get(tz, tz))\n")


def main(argv):
    src = Path(argv[1]) if len(argv) > 1 else Path("/usr/share/zoneinfo/zone.tab")
    places = parse_zone_tab(src.read_text(encoding="utf-8"))
    for a, b in ALIASES.items():
        assert b in places, f"alias {a} -> {b} is not in zone.tab"
    (HERE / "office_places.py").write_text(render(places), encoding="utf-8")
    print(f"wrote office_places.py: {len(places)} zones, {len(ALIASES)} aliases")


if __name__ == "__main__":
    main(sys.argv)
